// The screens a clean run never reaches on its own:  node tools/lastframe/uistates.mjs PORT OUT
import { chromium } from 'playwright-core';
import { CHROME, ANGLE } from '../chrome.mjs';
import fs from 'node:fs';
const [port, out] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: CHROME, headless: true, args: [ANGLE, '--enable-gpu', '--ignore-gpu-blocklist', '--use-gl=angle', '--autoplay-policy=no-user-gesture-required'] });
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto(`http://localhost:${port}/lastframe.html?dev=1`);
await p.waitForFunction(() => window.__lf, null, { timeout: 180000 });
await p.waitForTimeout(800);
await p.click('#m-solo');
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/setup.png` });
await p.setViewportSize({ width: 1280, height: 640 });
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/setup_short.png` });
await p.setViewportSize({ width: 1440, height: 900 });
await p.click('#s-go');
await p.waitForTimeout(6500);
await p.evaluate(() => {
  const g = __lf.g, u = g.hud;
  g.me.limp = 0.6; g.me.bleed = 2; g.me.arm = 0.4; g.me.hp = 42;
  g.match.players.find((q) => q.slot === g.mySlot).hp = 42; g.player(g.mySlot).hp = 42;
  u.feed('Hale', 'Vega', 0, 0, 0, 1, true); u.feed('Lund', 'Okafor', 2, 1, 1, 0, false); u.killed('Vega', 0, 41);
});
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/hud_hurt.png` });
await p.evaluate(() => { const g = __lf.g; g.match.damage(g.match.players.find((q) => q.slot !== g.mySlot && q.team !== 0).slot, g.mySlot, 200, 0, 0, [1, 0, 0], 23); });
await p.waitForTimeout(2600);
await p.screenshot({ path: `${out}/death.png` });
await p.evaluate(() => { const g = __lf.g; g.match.score = [40, 33]; g.match.finish(0); });
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/final.png` });
await p.click('.sh-acts button:last-child');
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/home_log.png` });
await b.close();
