// Real clicks, real keys, real pointer lock: menu to match.  node tools/lastframe/realinput.mjs PORT OUT
import { chromium } from 'playwright-core';
import { CHROME, ANGLE } from '../chrome.mjs';
import fs from 'node:fs';
const [port, out] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: CHROME, headless: true, args: [ANGLE, '--enable-gpu', '--ignore-gpu-blocklist', '--use-gl=angle', '--autoplay-policy=no-user-gesture-required'] });
const p = await (await b.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => m.type() === 'error' && !/GPU stall/.test(m.text()) && console.log('err', m.text().slice(0, 200)));
await p.goto(`http://localhost:${port}/lastframe.html`);
await p.waitForFunction(() => window.__lf, null, { timeout: 180000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/1_menu.png` });
await p.fill('#m-name', 'Reid');
await p.click('#m-solo');
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/2_setup.png` });
await p.click('[data-seg="bots"] [data-v="3"]');
await p.click('#s-go');
await p.waitForTimeout(2500);
console.log('locked', await p.evaluate(() => !!document.pointerLockElement), 'inMatch', await p.evaluate(() => __lf.g.inMatch));
await p.screenshot({ path: `${out}/3_match.png` });
const before = await p.evaluate(() => [__lf.g.me.m.x, __lf.g.me.m.z, __lf.g.me.yaw]);
await p.keyboard.down('KeyW');
await p.mouse.move(700, 360);
await p.mouse.move(760, 360, { steps: 6 });
await p.waitForTimeout(1200);
await p.keyboard.up('KeyW');
const after = await p.evaluate(() => [__lf.g.me.m.x, __lf.g.me.m.z, __lf.g.me.yaw]);
console.log('moved', before.map((v) => +v.toFixed(2)), '->', after.map((v) => +v.toFixed(2)));
await p.mouse.down();
await p.waitForTimeout(500);
await p.mouse.up();
console.log('ammo', await p.evaluate(() => __lf.g.me.ammo.get(__lf.g.me.weapon)));
// right button aims, left button fires, both at once fires aimed
const ads = () => p.evaluate(() => [+__lf.g.me.adsK.toFixed(2), +__lf.g.cam.fov.toFixed(1), __lf.g.input.ads, __lf.g.input.fire]);
await p.mouse.down({ button: 'right' });
await p.waitForTimeout(700);
console.log('right held', await ads());
await p.screenshot({ path: `${out}/3b_ads.png` });
const m0 = await p.evaluate(() => __lf.g.me.ammo.get(__lf.g.me.weapon).mag);
await p.mouse.down();
await p.waitForTimeout(300);
await p.mouse.up();
console.log('fired aimed', m0, '->', await p.evaluate(() => __lf.g.me.ammo.get(__lf.g.me.weapon).mag));
await p.mouse.up({ button: 'right' });
await p.waitForTimeout(600);
console.log('right released', await ads());
await p.keyboard.press('KeyZ');
await p.waitForTimeout(250);
console.log('kick', await p.evaluate(() => __lf.g.me.kickT));
await p.waitForTimeout(900);
await p.evaluate(() => { const g = __lf.g; g.me.hp = 60; g.match.players.find((q) => q.slot === g.mySlot).hp = 60; });
await p.keyboard.down('KeyH');
await p.waitForTimeout(1000);
await p.screenshot({ path: `${out}/3c_bandage.png` });
await p.waitForTimeout(2600);
await p.keyboard.up('KeyH');
console.log('bandage', await p.evaluate(() => [__lf.g.me.hp, __lf.g.me.wraps, __lf.g.match.players.find((q) => q.slot === __lf.g.mySlot).hp]));
await p.keyboard.press('KeyT');
await p.keyboard.press('KeyR');
await p.waitForTimeout(600);
console.log('light', await p.evaluate(() => __lf.g.me.light), 'reloading', await p.evaluate(() => __lf.g.me.reloadT > 0));
await p.keyboard.down('Tab');
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/4_board.png` });
await p.keyboard.up('Tab');
await p.evaluate(() => document.exitPointerLock());
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/5_pause.png` });
console.log('pause shown', await p.evaluate(() => document.querySelector('.pause').className));
await p.click('#p-leave');
await p.waitForTimeout(500);
console.log('left', await p.evaluate(() => [__lf.g.inMatch, document.querySelector('.menu').className]));
await b.close();
