// Walks the console picker with real keys: startup, press any button, login, home, tabs, pages. Usage: node tools/pickertest.mjs <outdir> [port]
import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
import { CHROME } from './chrome.mjs';
const out = process.argv[2] || 'shots', port = process.argv[3] || 5191;
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; page.on('pageerror', e => errs.push(String(e))); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const shot = n => page.screenshot({ path: `${out}/${n}.png` });
const wait = ms => page.waitForTimeout(ms);
const key = async (k, ms = 280) => { await page.keyboard.press(k); await wait(ms); };
const url = `http://localhost:${port}/?pick&boot`;
await page.goto(url); await page.evaluate(() => document.fonts.ready);
await wait(900); await shot('01_logo');
await wait(1500); await shot('02_warn');
await wait(1500); await shot('03_orb');
await wait(3200); await shot('04_press');
await wait(900); await shot('04b_press');
await key('Enter', 800); await shot('05_login');
await key('ArrowLeft', 400); await shot('05b_add');
await key('ArrowRight', 300);
await key('Enter', 1500); await shot('06_home');
await key('ArrowRight', 650); await shot('07_boost');
await key('ArrowRight', 650); await shot('08_miami');
await key('ArrowRight', 650); await shot('09_wobble');
await key('ArrowRight', 650); await shot('10_mogul');
await key('ArrowRight', 650); await shot('11_ts');
await key('ArrowRight', 650); await shot('12_lib');
await key('Enter', 500); await shot('13_libpage');
await key('Escape', 400);
await key('ArrowLeft', 500);
await key('ArrowDown', 300); await shot('14_playfocus');
await key('ArrowRight', 300); await key('Enter', 300); await shot('15_menu');
await key('Escape', 300); await key('ArrowLeft', 200);
await key('ArrowDown', 600); await shot('16_cards');
await key('ArrowUp', 500); await key('ArrowUp', 300);
await key('ArrowUp', 300); await shot('17_tabfocus');
await key('ArrowRight', 200); await key('Enter', 700); await shot('18_media');
await key('ArrowRight', 500); await key('Enter', 600); await shot('19_photo');
await key('Escape', 500);
await key('ArrowUp', 200); await key('ArrowRight', 200); await key('Enter', 400);
await page.keyboard.type('mi'); await wait(300); await shot('20_search');
await key('Escape', 300);
await key('ArrowRight', 200); await key('Enter', 400); await shot('21_settings');
await key('Escape', 300);
console.log(JSON.stringify({ errs }, null, 0));
await browser.close();
