// The career map's world: Natural Earth land (world-atlas 50m) and country borders (110m), projected
// with the Natural Earth I projection into map units and simplified, written to src/career/worldLand.ts.
//   node tools/build_world.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature, mesh } from 'topojson-client';

const W = 1000; // map width in units (x: −180 … 180)
const LAT_TOP = 78, LAT_BOT = -58; // Antarctica and the high Arctic cropped
const R = Math.PI / 180;
function ne1(lat, lon) {
  const p = lat * R, l = lon * R, p2 = p * p, p4 = p2 * p2;
  const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
  const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
  return [x, y];
}
const xMax = ne1(0, 180)[0];
const yTop = ne1(LAT_TOP, 0)[1], yBot = ne1(LAT_BOT, 0)[1];
const S = W / (2 * xMax);
const H = Math.round((yTop - yBot) * S);
const proj = (lon, lat) => { const [x, y] = ne1(Math.max(LAT_BOT - 4, Math.min(LAT_TOP + 4, lat)), lon); return [(x + xMax) * S, (yTop - y) * S]; };

const TOL = Number(process.env.TOL ?? 0.25);
function simplify(pts) {
  // radial distance then Douglas–Peucker
  const r = [pts[0]];
  for (const p of pts) { const q = r[r.length - 1]; if (Math.hypot(p[0] - q[0], p[1] - q[1]) > TOL * 0.5) r.push(p); }
  const keep = new Uint8Array(r.length); keep[0] = keep[r.length - 1] = 1;
  // (a closed ring starts and ends on the same point: split it at the point farthest from the start)
  let far = 0, fd = -1;
  for (let i = 1; i < r.length - 1; i++) { const d = Math.hypot(r[i][0] - r[0][0], r[i][1] - r[0][1]); if (d > fd) { fd = d; far = i; } }
  const st = far > 0 ? [[0, far], [far, r.length - 1]] : [[0, r.length - 1]];
  if (far > 0) keep[far] = 1;
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    const [ax, ay] = r[a], [bx, by] = r[b]; const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs((r[i][0] - ax) * dy - (r[i][1] - ay) * dx) / L; if (d > md) { md = d; mi = i; } }
    if (md > TOL && mi > 0) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return r.filter((_, i) => keep[i]);
}
const area = (pts) => { let s = 0; for (let i = 0; i < pts.length; i++) { const a = pts[i], b = pts[(i + 1) % pts.length]; s += a[0] * b[1] - b[0] * a[1]; } return Math.abs(s / 2); };
const f = (n) => (Math.round(n * 10) / 10).toString();
function ringPath(ring, close) {
  // (unwrapped across the antimeridian: Chukotka's ring stays one piece east of 180°, not a band across the map)
  let off = 0, prev = ring[0][0];
  const un = ring.map(([lo, la]) => {
    if (lo + off - prev > 180) off -= 360;
    else if (lo + off - prev < -180) off += 360;
    prev = lo + off;
    return [lo + off, la];
  });
  const pts = simplify(un.map(([lo, la]) => proj(lo, la)));
  if (pts.length < (close ? 4 : 2)) return '';
  if (close && area(pts) < 1.2) return '';
  let d = '', px = 0, py = 0;
  pts.forEach(([x, y], i) => {
    const X = Math.round(x * 10), Y = Math.round(y * 10);
    // relative moves keep the string short
    d += i === 0 ? `M${f(x)} ${f(y)}` : `l${f((X - px) / 10)} ${f((Y - py) / 10)}`;
    px = X; py = Y;
  });
  return d + (close ? 'z' : '');
}
const land = feature(JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8')), 'land');
let landD = '';
let nr = 0, nk = 0;
for (const g of land.features) {
  const polys = g.geometry.type === 'Polygon' ? [g.geometry.coordinates] : g.geometry.coordinates;
  for (const poly of polys) for (const ring of poly) {
    if (ring.every(([, la]) => la < -60)) continue;
    const rp = ringPath(ring, true); nr++; if (rp) nk++; landD += rp;
  }
}
const ctop = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'));
const borders = mesh(ctop, ctop.objects.countries, (a, b) => a !== b);
let bordD = '';
for (const line of borders.coordinates) bordD += ringPath(line, false);
// graticule: every 15° of latitude and 30° of longitude
let grat = '';
for (let la = -45; la <= 75; la += 15) { const pts = []; for (let lo = -180; lo <= 180; lo += 5) pts.push([lo, la]); grat += ringPath(pts, false); }
for (let lo = -180; lo <= 180; lo += 30) { const pts = []; for (let la = LAT_BOT; la <= LAT_TOP; la += 3) pts.push([lo, la]); grat += ringPath(pts, false); }
const outline = (() => { const pts = []; for (let la = LAT_BOT; la <= LAT_TOP; la += 2) pts.push(proj(-180, la)); for (let la = LAT_TOP; la >= LAT_BOT; la -= 2) pts.push(proj(180, la)); return 'M' + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'z'; })();

const src = `// generated by tools/build_world.mjs from Natural Earth (world-atlas, public domain) — do not edit
/** map width / height in units */
export const WORLD_W = ${W};
export const WORLD_H = ${H};
/** Natural Earth I projection constants (lat ${LAT_TOP} … ${LAT_BOT}) */
export const WORLD_PROJ = { s: ${S.toFixed(6)}, xMax: ${xMax.toFixed(6)}, yTop: ${yTop.toFixed(6)} };
export const WORLD_LAND = '${landD}';
export const WORLD_BORDERS = '${bordD}';
export const WORLD_GRATICULE = '${grat}';
export const WORLD_OUTLINE = '${outline}';
`;
writeFileSync('src/career/worldLand.ts', src);
console.log('rings', nr, nk, 'H', H, 'land', landD.length, 'borders', bordD.length, 'grat', grat.length, 'total KB', (src.length / 1024).toFixed(0));
